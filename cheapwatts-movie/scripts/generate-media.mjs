// Scans public/vo for voiceover files named after scene ids (hook.wav,
// pick.wav, ...), measures each one, and writes src/generated-media.ts so
// every scene stretches to fit its narration. Missing files are fine: the
// scene keeps its default length and plays without voice.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, extname, basename } from "node:path";
import { parseMedia } from "@remotion/media-parser";
import { nodeReader } from "@remotion/media-parser/node";

const root = new URL("..", import.meta.url).pathname;
const voDir = join(root, "public", "vo");
const files = existsSync(voDir)
  ? readdirSync(voDir).filter((f) => [".wav", ".mp3", ".m4a"].includes(extname(f).toLowerCase()))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }))
  : [];

const vo = {};
for (const f of files) {
  try {
    const { durationInSeconds } = await parseMedia({
      src: join(voDir, f), fields: { durationInSeconds: true }, reader: nodeReader, acknowledgeRemotionLicense: true,
    });
    vo[basename(f, extname(f))] = { file: `vo/${f}`, seconds: Number(durationInSeconds.toFixed(3)) };
  } catch (e) {
    console.warn(`Skipping ${f}: ${e.message}`);
  }
}

// Optional background music: public/music.mp3 (or .m4a/.wav).
const music = ["music.mp3", "music.m4a", "music.wav"].find((f) => existsSync(join(root, "public", f))) ?? null;

writeFileSync(join(root, "src", "generated-media.ts"),
  `// Generated by scripts/generate-media.mjs. Do not edit; run "npm run scan".\n` +
  `export const VO: Record<string, { file: string; seconds: number }> = ${JSON.stringify(vo, null, 2)};\n` +
  `export const MUSIC: string | null = ${JSON.stringify(music)};\n`);
console.log(`Voiceover found for: ${Object.keys(vo).join(", ") || "none (captions-only cut)"}`);
